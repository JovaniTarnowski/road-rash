#!/usr/bin/env python3
"""Handoff index for docs/agent-handoffs (plan 31 Task 2).

For each handoff: title (first heading), date (filename or mtime), whether it
is cited in docs/*.md, docs/plans/*.md or git log messages (merged), and
whether it mentions live resources (open). --write regenerates INDEX.md;
--archive moves merged, resource-free handoffs to archive/YYYY-MM/ and rewrites
links in docs/ (plain string replacement of the relative path).
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HANDOFFS = ROOT / 'docs' / 'agent-handoffs'

RESOURCE_RE = re.compile(r'\b(PID|pid|lock|claim)\b[^\n]*(released|none)\b', re.S)


def live_resources(text):
    for m in re.finditer(r'\b(PIDs?|pids?|lock|claim)\b', text, re.I):
        tail = text[m.start():m.start() + 120]
        if not re.search(r'released|none', tail, re.I):
            return True
    return False


def classify(name, text, docs_text, log_text):
    cited = name in docs_text or name in log_text
    if cited:
        return 'merged'
    if live_resources(text):
        return 'open (resources)'
    return 'open'


def collect(root=ROOT):
    hands = root / 'docs' / 'agent-handoffs'
    docs_text = ''
    for doc in list((root / 'docs').glob('*.md')) + list((root / 'docs' / 'plans').glob('*.md')):
        try:
            docs_text += doc.read_text()
        except OSError:
            continue
    try:
        log_text = subprocess.run(['git', '-C', str(root), 'log', '--all', '--format=%B'],
                                  capture_output=True, text=True).stdout
    except OSError:
        log_text = ''
    rows = []
    for path in sorted(hands.glob('*.md')):
        if path.name == 'INDEX.md':
            continue
        try:
            text = path.read_text()
        except OSError:
            continue
        title = next((l.lstrip('# ').strip() for l in text.split('\n') if l.startswith('#')), path.name)
        m = re.match(r'(\d{4}-\d{2}-\d{2})', path.name)
        date = m.group(1) if m else ''
        rows.append({'file': path.name, 'title': title, 'date': date,
                     'status': classify(path.name, text, docs_text, log_text)})
    return rows


def write_index(rows, root=ROOT):
    lines = ['# Handoff index', '',
             'Generated by `python3 tools/handoff_index.py --write`. `merged` = cited in docs or commit messages; `open` = not yet folded in.',
             '', '| File | Date | Status | Title |', '| --- | --- | --- | --- |']
    for r in rows:
        lines.append(f"| {r['file']} | {r['date']} | {r['status']} | {r['title']} |")
    (root / 'docs' / 'agent-handoffs' / 'INDEX.md').write_text('\n'.join(lines) + '\n')


def archive(rows, root=ROOT):
    import datetime
    moved = []
    for r in rows:
        if r['status'] != 'merged':
            continue
        src = root / 'docs' / 'agent-handoffs' / r['file']
        try:
            text = src.read_text()
        except OSError:
            continue
        if live_resources(text):
            continue  # Review Focus 1: resources may still be held
        dest = root / 'docs' / 'agent-handoffs' / 'archive' / datetime.date.today().strftime('%Y-%m') / r['file']
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(src), str(dest))
        old, new = 'agent-handoffs/' + r['file'], 'agent-handoffs/archive/' + dest.parent.name + '/' + r['file']
        for doc in list((root / 'docs').glob('*.md')) + list((root / 'docs' / 'plans').glob('*.md')):
            try:
                t = doc.read_text()
            except OSError:
                continue
            if old in t:
                doc.write_text(t.replace(old, new))
        moved.append(r['file'])
    return moved


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write', action='store_true')
    p.add_argument('--archive', action='store_true')
    args = p.parse_args()
    rows = collect()
    if args.write:
        write_index(rows)
    if args.archive:
        for f in archive(rows):
            print(f'archived {f}')
    if not args.write and not args.archive:
        for r in rows:
            print(f"{r['status']:16} {r['file']}  {r['title'][:60]}")


if __name__ == '__main__':
    main()
