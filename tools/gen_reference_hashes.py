#!/usr/bin/env python3
"""Generate path/hash metadata only; never include original game bytes."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
inventory = json.loads((root / 'analysis/inventory.json').read_text())
lines = ['// Generated by tools/gen_reference_hashes.py; SHA-256 metadata only.']
for entry in sorted(inventory['files'], key=lambda e: e['path']):
    path, digest = entry['path'], entry['sha256']
    assert not Path(path).is_absolute() and '..' not in Path(path).parts
    assert len(digest) == 64 and set(digest) <= set('0123456789abcdef')
    lines.append('{' + json.dumps(path) + ', ' + json.dumps(digest) + '},')
(root / 'src/reference_hashes.inc').write_text('\n'.join(lines) + '\n')
print(f'Generated {len(inventory["files"])} reference hashes')
